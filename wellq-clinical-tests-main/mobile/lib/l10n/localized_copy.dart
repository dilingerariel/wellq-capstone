String localizedExamLabel(BuildContext c, String status, {String? review}) =>
    c.l10n.safeMessage(domain.examLabel(status, review: review));
String? localizedTestTypeLabel(BuildContext c, String? type) {
  final key = domain.testTypeLabel(type);
  return key == null ? null : c.l10n.safeMessage(key);
}

String localizedExtractionLabel(BuildContext c, String status) =>
    c.l10n.safeMessage(domain.extractionLabel(status));
String localizedPhaseLabel(BuildContext c, String phase) =>
    c.l10n.safeMessage(model.phaseLabel(phase));
String localizedPendingHelp(
  BuildContext c,
  String phase, {
  String? error,
  bool retryScheduled = false,
}) => c.l10n.safeMessage(
  domain.pendingHelp(phase, error: error, retryScheduled: retryScheduled),
);
String localizedClinicalDate(BuildContext c, String raw) {
  final value = clinicalDate(raw, locale: c.l10n.localeName);
  return value == 'dateUnavailable' ? c.l10n.dateUnavailable : value;
}

String localizedConfirmationTime(BuildContext c, String raw) {
  final value = confirmationTime(raw, locale: c.l10n.localeName);
  return value == 'timeUnavailable' ? c.l10n.timeUnavailable : value;
}
